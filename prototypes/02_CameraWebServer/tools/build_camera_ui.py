"""Embed the settings script and add it to the existing vendor camera pages.

Run from any directory with Python 3. Re-running produces identical output.
The vendor pages stay in camera_index.h; their original HTML and script remain
unchanged apart from the additional external script tag.
"""
import gzip
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "src" / "camera_index.h"
TAG = '<script defer src="/camera_settings.js"></script>'


def build():
    header = HEADER.read_text(encoding="utf-8")
    names = re.findall(r"const unsigned char (\w+)\[\] = \{", header)
    assert len(names) == 3, "Expected all three vendor camera pages"
    for name in names:
        pattern = rf"const unsigned char {name}\[\] = \{{(.*?)\}};"
        body = re.search(pattern, header, re.S).group(1)
        data = bytes(int(n, 16) for n in re.findall(r"0x([0-9a-fA-F]{2})", body))
        html = gzip.decompress(data).decode("utf-8")
        if TAG not in html:
            assert "</head>" in html
            html = html.replace("</head>", TAG + "\n</head>", 1)
        data = gzip.compress(html.encode("utf-8"), compresslevel=9, mtime=0)
        rows = ["  " + ", ".join(f"0x{x:02X}" for x in data[i:i+24]) + "," for i in range(0, len(data), 24)]
        array = f"const unsigned char {name}[] = {{\n" + "\n".join(rows) + "\n};"
        header = re.sub(pattern, lambda _: array, header, flags=re.S)
        header = re.sub(rf"(#define {name}_len) \d+", rf"\g<1> {len(data)}", header)
        filename = name.replace("_html_gz", ".html.gz")
        header = re.sub(rf"(//File: {re.escape(filename)}, Size:) \d+", rf"\g<1> {len(data)}", header)
    HEADER.write_text(header, encoding="utf-8", newline="\n")
    script = (ROOT / "web" / "camera_settings.js").read_text(encoding="utf-8")
    assert ')golfcam"' not in script
    (ROOT / "src" / "camera_settings_ui.h").write_text(
        '// Generated by tools/build_camera_ui.py; edit web/camera_settings.js.\n'
        '#pragma once\nstatic const char camera_settings_js[] = R"golfcam('
        + script + ')golfcam";\n', encoding="utf-8", newline="\n")


if __name__ == "__main__":
    build()
